export function makeDropZone({ accept, multiple, onFiles, title, hint }) {
  const el = document.createElement('div');
  el.className = 'drop-zone';
  el.tabIndex = 0;
  el.setAttribute('role', 'button');
  el.innerHTML = icon('upload', 40)
    + '<div class="dz-title">' + title + '</div>'
    + '<div class="dz-hint">' + hint + '</div>'
    + '<input type="file" class="hidden" ' + (multiple ? 'multiple' : '') + ' accept="' + accept + '" />';
  const input = el.querySelector('input');
  el.addEventListener('click', () => input.click());
  el.addEventListener('keydown', (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); input.click(); } });
  el.addEventListener('dragover', (e) => { e.preventDefault(); el.classList.add('drag'); });
  el.addEventListener('dragleave', () => el.classList.remove('drag'));
  el.addEventListener('drop', (e) => {
    e.preventDefault(); el.classList.remove('drag');
    const files = [...e.dataTransfer.files].filter((f) => matchesAccept(f, accept));
    if (files.length) onFiles(files); else toast('Unsupported file type', 'error');
  });
  input.addEventListener('change', (e) => {
    const files = [...e.target.files];
    if (files.length) onFiles(files);
    e.target.value = '';
  });
  return el;
}

export function matchesAccept(file, accept) {
  if (!accept) return true;
  return accept.split(',').some((rule) => {
    rule = rule.trim();
    if (rule === 'image/*') return file.type.startsWith('image/');
    if (rule === 'video/*') return file.type.startsWith('video/');
    if (rule === 'application/pdf') return file.type === 'application/pdf' || file.name.toLowerCase().endsWith('.pdf');
    return file.type === rule;
  });
}

export function escapeHTML(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;' }[c]));
}